  /// Get translated string by key.
  static String tr(BuildContext context, String key) {
    // Read the ACTIVE locale: prefer the one user picked (persisted),
    // fall back to the widget tree locale (may be null without delegates).
    final saved = StorageService.locale;
    final locale = (saved != null && saved.isNotEmpty)
        ? saved
        : (Localizations.maybeLocaleOf(context)?.languageCode ?? 'en');
    final langMap = _translations[locale] ?? _translations['en']!;
    return langMap[key] ?? _translations['en']![key] ?? key;
  }

  /// Get translation without context (use language code directly).
  static String t(String langCode, String key) {
    final langMap = _translations[langCode] ?? _translations['en']!;
    return langMap[key] ?? _translations['en']![key] ?? key;
  }
}

/// Global shortcut — screens import the file and call tr(context, 'key').
String tr(BuildContext context, String key) => AppLocalizations.tr(context, key);
